"""
Bio-Thermal Physics Engine (Advanced Psychrometric Model)
---------------------------------------------------------
Calculates sensible and latent thermal energy recovery from geospatial data.
Applies the Ideal Gas Law for dynamic air density adjustments based on local
barometric pressure and incorporates biothermal enthalpy coefficients to 
account for avian macroscopic thermogenesis and moisture loads.
"""

import pandas as pd

class BioThermalEngine:
    """
    Advanced thermodynamic modeling framework for microclimate heat recovery.
    """
    
    # Thermophysical & Environmental Constants
    CP_AIR = 1.005             # Specific heat capacity of dry air (kJ/kg.K)
    R_SPECIFIC = 287.058       # Specific gas constant for dry air (J/kg.K)
    PHOENIX_PRESSURE_PA = 97500  # Approx atmospheric pressure at 330m elevation (Pascals)
    
    LPG_ENERGY_DENSITY = 25.3  # Average energy density of LPG (kWh/liter)
    CO2_EMISSION_FACTOR = 1.51 # Carbon footprint (kg CO2e per liter of LPG)

    def __init__(self, heat_exchanger_efficiency: float = 0.65):
        """
        Initializes the engine.
        
        Args:
            heat_exchanger_efficiency (float): Operational transfer matrix (0.0 to 1.0).
        """
        self.efficiency = heat_exchanger_efficiency

    def compute_dynamic_density(self, air_temp_c: float) -> float:
        """
        Calculates dynamic air density using the Ideal Gas Law.
        Equation: ρ = P / (R * T)
        """
        temp_k = air_temp_c + 273.15
        return self.PHOENIX_PRESSURE_PA / (self.R_SPECIFIC * temp_k)

    def compute_mass_flow_rate(self, airflow_m3h: float, exhaust_temp_c: float) -> float:
        """
        Converts volumetric flow rate to mass flow rate based on exhaust conditions.
        """
        dynamic_rho = self.compute_dynamic_density(exhaust_temp_c)
        return (airflow_m3h / 3600.0) * dynamic_rho

    def calculate_recoverable_power(
        self, 
        ambient_temp: float, 
        exhaust_temp: float, 
        airflow_m3h: float, 
        facility_type: str
    ) -> float:
        """
        Calculates total heat recovery, incorporating latent heat multipliers 
        for highly saturated biological exhaust plumes.
        """
        if airflow_m3h <= 0 or exhaust_temp <= ambient_temp:
            return 0.0
            
        m_dot = self.compute_mass_flow_rate(airflow_m3h, exhaust_temp)
        delta_t = exhaust_temp - ambient_temp
        
        # Base sensible heat calculation (Q = ṁ * Cp * ΔT)
        sensible_power_kw = m_dot * self.CP_AIR * delta_t
        
        # Biothermal Enthalpy Adjustment
        # Biological facilities output massive latent heat (respiratory moisture).
        # Standard industrial exhaust is largely dry sensible heat.
        if facility_type == "poultry_shed":
            latent_multiplier = 1.35  # Empirical moisture/enthalpy factor for avian environments
        else:
            latent_multiplier = 1.0   # Dry exhaust baseline
            
        total_power_kw = sensible_power_kw * latent_multiplier * self.efficiency
        return total_power_kw

    def calculate_annual_impact(self, power_kw: float, facility_type: str) -> dict:
        """
        Projects immediate kilowatt recovery into annualized environmental metrics,
        adjusting operational hours based on seasonal brooding cycles.
        """
        # Poultry sheds don't vent at 100% capacity year-round; fans scale with bird age.
        operational_hours = 5200 if facility_type == "poultry_shed" else 8760
        
        annual_energy_kwh = power_kw * operational_hours
        lpg_liters_offset = annual_energy_kwh / self.LPG_ENERGY_DENSITY
        co2_offset_kg = lpg_liters_offset * self.CO2_EMISSION_FACTOR
        
        return {
            "annual_energy_kwh": round(annual_energy_kwh, 2),
            "lpg_liters_offset": round(lpg_liters_offset, 2),
            "co2_offset_tons": round(co2_offset_kg / 1000.0, 4)
        }

    def process_spatial_dataframe(self, df: pd.DataFrame) -> pd.DataFrame:
        """
        Iterates over the spatial dataframe generated by the API client,
        appending mathematically verified thermodynamic parameters to each node.
        """
        powers = []
        annual_kwh = []
        co2_tons = []
        
        for _, row in df.iterrows():
            ambient = row.get('air_temp_c', 25.0)
            exhaust = row.get('exhaust_air_temp_c', 0.0)
            airflow = row.get('ventilation_airflow_m3h', 0.0)
            facility = row.get('facility_type', 'unknown')
            
            p_kw = self.calculate_recoverable_power(ambient, exhaust, airflow, facility)
            impact = self.calculate_annual_impact(p_kw, facility)
            
            powers.append(round(p_kw, 2))
            annual_kwh.append(impact['annual_energy_kwh'])
            co2_tons.append(impact['co2_offset_tons'])
            
        df['recoverable_power_kw'] = powers
        df['annual_recovery_kwh'] = annual_kwh
        df['annual_co2_offset_tons'] = co2_tons
        
        return df

